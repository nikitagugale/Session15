// The hidden answer key for the BEHAVIOUR of src/bopis/eligibility.js. Everything the checks believe about the code comes from here.
//
// core(cfg, item, ctx) is the whole rule set, with switches. `REFERENCE` is what the code should do after milestone 5 (the perishable
// rule added, nothing else changed). A "mutant" is the same code with one rule made slightly wrong; a requirement test that does not
// notice a mutant is not testing what it is named after. `variantSource` turns a switch setting into the source text of a module.
//
// This file is outside the folder learners open on purpose: it holds the answers.

/* eslint-disable */
function core(cfg, item, ctx) {
  const { quantity = 1, storeStock = Infinity, storeOpen = true, ageVerified = false } = ctx;
  if (cfg.storeOpen && !storeOpen) return false;
  if (cfg.gift && item.category === 'gift-card') return false;
  if (cfg.hazmat && item.hazmat) return false;
  if (cfg.age && item.ageRestricted && !ageVerified) return false;
  if (quantity > cfg.maxQty) return false;
  if (cfg.stockOp === '<=' ? storeStock <= quantity + cfg.buffer : storeStock < quantity + cfg.buffer) return false;
  if (cfg.highValueOp === '>=' ? item.price >= cfg.highValue : item.price > cfg.highValue) return false;
  if (cfg.perishable === 'category' && ['produce', 'dairy', 'meat', 'frozen', 'bakery'].includes(item.category)) return false;
  if (cfg.perishable === 'noFrozen' && ['produce', 'dairy', 'meat', 'bakery'].includes(item.category)) return false;
  if (cfg.perishable === 'noBakery' && ['produce', 'dairy', 'meat', 'frozen'].includes(item.category)) return false;
  if (cfg.perishable === 'withPantry' && ['produce', 'dairy', 'meat', 'frozen', 'bakery', 'pantry'].includes(item.category)) return false;
  if (cfg.perishable === 'shelf' && item.shelfLifeDays != null && item.shelfLifeDays <= 7) return false;
  if (cfg.weight === 'over20' && item.weightKg > 20) return false;
  if (cfg.weight === 'atLeast20' && item.weightKg >= 20) return false;
  if (cfg.weight === 'over25' && item.weightKg > 25) return false;
  if (cfg.recall && item.supplier_recall) return false;
  return true;
}
/* eslint-enable */

/** The code as delivered: no perishable rule, no weight rule, no recall rule. */
export const PRISTINE = { storeOpen: true, gift: true, hazmat: true, age: true, maxQty: 6, buffer: 2, stockOp: '<', highValue: 2000, highValueOp: '>', perishable: 'none', weight: 'none', recall: false };
/** What the code should be after milestone 5. */
export const REFERENCE = { ...PRISTINE, perishable: 'category' };
/** What the code should be after the homework. */
export const WITH_WEIGHT = { ...REFERENCE, weight: 'over20' };
/** What the demo adds on top of the delivered code. */
export const WITH_RECALL = { ...PRISTINE, recall: true };

export const make = cfg => (item, ctx = {}) => core(cfg, item, ctx);

export function variantSource(cfg) {
  return `// generated by the lab's checks\nconst cfg = ${JSON.stringify(cfg)};\n${core.toString()}\nexport function isBopisEligible(item, ctx = {}) { return core(cfg, item, ctx); }\n`;
}

